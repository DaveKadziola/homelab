#!/usr/bin/env python3
"""Generate the Caddyfile and the Authelia access/session config from config/services.yml.

  utils/gen-proxy-config.py --env dev --file caddyfile|authelia|adguard|list
  utils/gen-proxy-config.py --self-test

Every service with an HTTP(S) check gets the name <subdomain>.<environments.<env>.domain> (subdomain
defaults to the service name) unless `proxy: false`, it has a `public_url` (Grocery stays on the
OPNsense HAProxy) or its compose profile is off for the env (same defaults as deploy-core.yml).
Caddy serves one wildcard site: DEV with its internal CA, prod with a Let's Encrypt wildcard
certificate through the Cloudflare DNS challenge (CLOUDFLARE_API_TOKEN). Each name goes through
Authelia (forward_auth) except what `auth_bypass` lists: `all`, or path regexes for the apps' own
API clients. Output on stdout:
  caddyfile  compose/core/caddy/Caddyfile
  authelia   compose/core/authelia/access.yml (session cookie + access_control)
  adguard    one `name ip` line per name, for the AdGuard rewrites (utils/adguard-rewrites.sh)
  list       `name<TAB>bypass` per proxied service, for the tests
Exit code: 0 ok, 1 self-test failed, 2 usage or config error.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def proxied(services, env, profiles):
    """[(service dict, host name)] in services.yml order."""
    on = set(profiles.split(","))
    domain = env["domain"]
    out = []
    for s in services:
        if s.get("check") not in ("http", "https") or s.get("proxy") is False or s.get("public_url"):
            continue
        if s.get("profile") and s["profile"] not in on:
            continue
        out.append((s, f"{s.get('subdomain', s['name'])}.{domain}"))
    return out


def caddyfile(services, env, env_name, profiles):
    domain = env["domain"]
    if env_name == "prod":
        # Port 53 from APP is redirected to AdGuard (docs/network.md), which answered SERVFAIL for the
        # challenge TXT record, so Caddy's own propagation check never passed. Let's Encrypt queries
        # Cloudflare itself; Caddy only waits before it asks.
        tls = ("\ttls {\n\t\tdns cloudflare {env.CLOUDFLARE_API_TOKEN}\n\t\tresolvers 1.1.1.1\n"
               "\t\tpropagation_delay 60s\n\t\tpropagation_timeout -1\n\t}")
    else:
        tls = "\ttls internal"
    lines = [
        "# Generated by utils/gen-proxy-config.py from config/services.yml - do not edit.",
        "(authelia) {",
        "\tforward_auth authelia:9091 {",
        "\t\turi /api/authz/forward-auth",
        "\t\tcopy_headers Remote-User Remote-Groups Remote-Email Remote-Name",
        "\t}",
        "}",
        "",
        f"*.{domain} {{",
        tls,
        "",
        f"\t@auth host auth.{domain}",
        "\thandle @auth {",
        "\t\treverse_proxy authelia:9091",
        "\t}",
    ]
    for s, host in proxied(services, env, profiles):
        upstream = f"host.docker.internal:{s['port']}"
        lines += ["", f"\t@{s['name']} host {host}", f"\thandle @{s['name']} {{"]
        if s.get("auth_bypass") != "all":
            lines.append("\t\timport authelia")
        if s["check"] == "https":
            lines += [f"\t\treverse_proxy https://{upstream} {{", "\t\t\ttransport http {",
                      "\t\t\t\ttls_insecure_skip_verify", "\t\t\t}", "\t\t}"]
        else:
            lines.append(f"\t\treverse_proxy {upstream}")
        lines.append("\t}")
    lines += ["", "\thandle {", '\t\trespond "unknown name" 404', "\t}", "}", ""]
    return "\n".join(lines)


def authelia(services, env, env_name, profiles):
    domain = env["domain"]
    rules = []
    for s, host in proxied(services, env, profiles):
        bypass = s.get("auth_bypass")
        if bypass == "all":
            rules.append(f"    - domain: '{host}'\n      policy: bypass")
        elif bypass:
            res = "".join(f"\n        - '{r}'" for r in bypass)
            rules.append(f"    - domain: '{host}'\n      resources:{res}\n      policy: bypass")
    rules.append(f"    - domain: '*.{domain}'\n      policy: one_factor")
    return (
        "# Generated by utils/gen-proxy-config.py from config/services.yml - do not edit.\n"
        # The DEV domain sits under the prod one: one cookie name each, or a prod session is sent to
        # DEV and breaks its login.
        f"session:\n  cookies:\n    - name: authelia_session_{env_name}\n"
        f"      domain: '{domain}'\n      authelia_url: 'https://auth.{domain}'\n"
        "      expiration: 12h\n      inactivity: 1h\n"
        "access_control:\n  default_policy: deny\n  rules:\n" + "\n".join(rules) + "\n"
    )


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--env", choices=["dev", "prod"])
    parser.add_argument("--file", choices=["caddyfile", "authelia", "adguard", "list"])
    parser.add_argument("--profiles", help="enabled compose profiles (default: services.yml environments.<env>.profiles)")
    parser.add_argument("--self-test", action="store_true", help="test the generators, no config files")
    args = parser.parse_args(argv)
    if args.self_test:
        return self_test()
    if not args.env or not args.file:
        parser.error("--env and --file are required")
    import yaml  # noqa: PLC0415 - not needed by the self-test
    doc = yaml.safe_load(open(ROOT / "config" / "services.yml"))
    env = doc["environments"][args.env]
    if not env.get("domain"):
        print(f"error: config/services.yml environments.{args.env}.domain is empty", file=sys.stderr)
        return 2
    profiles = args.profiles or env.get("profiles", "")
    services = doc["services"]
    if args.file == "caddyfile":
        sys.stdout.write(caddyfile(services, env, args.env, profiles))
    elif args.file == "authelia":
        sys.stdout.write(authelia(services, env, args.env, profiles))
    elif args.file == "adguard":
        for host in [f"auth.{env['domain']}"] + [h for _, h in proxied(services, env, profiles)]:
            print(f"{host} {env['host']}")
    else:
        for s, host in proxied(services, env, profiles):
            bypass = s.get("auth_bypass") or ""
            print(f"{host}\t{bypass if isinstance(bypass, str) else ','.join(bypass)}")
    return 0


def self_test():
    env = {"host": "10.0.0.5", "domain": "dev.example.org"}
    services = [
        {"name": "postgres", "check": "tcp", "port": 5432},
        {"name": "homarr", "check": "http", "port": 7575},
        {"name": "authelia", "check": "http", "port": 9091, "profile": "auth", "proxy": False},
        {"name": "jellyfin", "check": "http", "port": 8096, "profile": "media", "auth_bypass": "all"},
        {"name": "immich", "check": "http", "port": 2283, "profile": "media", "auth_bypass": ["^/api([/?].*)?$"]},
        {"name": "grocery", "check": "http", "port": 8101, "public_url": "https://grocery.example.org"},
        {"name": "mailpit", "check": "http", "port": 8025, "profile": "devmail"},
        {"name": "portainer", "check": "https", "port": 9443, "subdomain": "docker"},
    ]
    names = [h for _, h in proxied(services, env, "auth,media")]
    assert names == ["homarr.dev.example.org", "jellyfin.dev.example.org", "immich.dev.example.org",
                     "docker.dev.example.org"], names
    assert "mailpit.dev.example.org" in [h for _, h in proxied(services, env, "media,devmail")]

    c = caddyfile(services, env, "dev", "auth,media")
    assert "*.dev.example.org {" in c and "\ttls internal" in c and "cloudflare" not in c
    jf = c.split("@jellyfin host")[1].split("\t}")[0]
    assert "import authelia" not in jf and "reverse_proxy host.docker.internal:8096" in jf, jf
    hm = c.split("@homarr host")[1].split("\t}")[0]
    assert "import authelia" in hm, hm
    assert "reverse_proxy https://host.docker.internal:9443 {" in c and "tls_insecure_skip_verify" in c
    assert c.count("{") == c.count("}"), "unbalanced braces"
    p = caddyfile(services, env, "prod", "auth,media")
    assert "dns cloudflare {env.CLOUDFLARE_API_TOKEN}" in p and "\t\tpropagation_timeout -1\n" in p
    assert p.count("{") == p.count("}"), "unbalanced braces (prod)"

    a = authelia(services, env, "dev", "auth,media")
    import yaml  # noqa: PLC0415 - parse what Authelia will parse
    try:
        doc = yaml.safe_load(a)
    except Exception as e:  # noqa: BLE001
        raise AssertionError(f"authelia output is not YAML: {e}") from None
    rules = doc["access_control"]["rules"]
    assert doc["access_control"]["default_policy"] == "deny"
    assert rules[0] == {"domain": "jellyfin.dev.example.org", "policy": "bypass"}, rules
    assert rules[1]["resources"] == ["^/api([/?].*)?$"] and rules[1]["policy"] == "bypass", rules
    assert rules[-1] == {"domain": "*.dev.example.org", "policy": "one_factor"}, rules
    assert doc["session"]["cookies"][0]["authelia_url"] == "https://auth.dev.example.org"
    assert doc["session"]["cookies"][0]["name"] == "authelia_session_dev"
    print("self-test ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
